import { describe, expect, it } from "vitest";
import { resolveServerSupabaseConfig } from "./config";

describe("Supabase environment resolution", () => {
  it("uses manually configured public variables", () => {
    expect(resolveServerSupabaseConfig({
      NEXT_PUBLIC_SUPABASE_URL: "https://manual.supabase.co",
      NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: "publishable-key",
    })).toEqual({
      url: "https://manual.supabase.co",
      publishableKey: "publishable-key",
    });
  });

  it("uses the server-side variables generated by the prefixed Vercel integration", () => {
    expect(resolveServerSupabaseConfig({
      supabase_POSTGRES_HOST: "db.project-ref.supabase.co",
      supabase_SUPABASE_ANON_KEY: "anon-key",
    })).toEqual({
      url: "https://project-ref.supabase.co",
      publishableKey: "anon-key",
    });
  });

  it("returns null when no complete public configuration can be resolved", () => {
    expect(resolveServerSupabaseConfig({ supabase_POSTGRES_HOST: "pooler.supabase.com" })).toBeNull();
  });
});
